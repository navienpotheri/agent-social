/**
 * Generates `docs/enterprise/pricing-inputs.md` (register row DK1363): the cost inputs of an agent of a fleet that have been MEASURED, worked out per agent for a month at three act rates from the load test of
 * DK1362 (`docs/load-test-results-fleet.json`), next to the list of what has not been measured and the structure of a plan with who decides each part. It names no price, no margin and no currency: the owner's
 * decision of 2026-11-21 is that no figure is published until the cost per fleet agent has been measured on the hosted service. Deterministic. Run with `npm run pricing-inputs`; a test compares the file.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));

export function pricingInputs(): string {
  const r = JSON.parse(readFileSync(join(root, "docs", "load-test-results-fleet.json"), "utf8")) as { when: string; agents: number; totals: { msPerWrite: number; writesPerSecondOneProcess: number; bytesPerRecord: number }; cost: { cpuSecondsPerMillionWrites: number; gigabytesPerMillionRecords: number } };
  const cpuPerWrite = r.cost.cpuSecondsPerMillionWrites / 1_000_000;
  const row = (actsPerDay: number) => {
    const writes = actsPerDay * 30;
    const cpu = writes * cpuPerWrite;
    const mb = (writes * r.totals.bytesPerRecord) / 1_000_000;
    return `| ${actsPerDay} | ${writes.toLocaleString("en-GB")} | ${cpu.toFixed(2)} | ${mb.toFixed(2)} |`;
  };
  return `# Pricing inputs for the plans (register row DK1363): what has been measured, and what has not

**Status: a draft for the owner, generated by \`npm run pricing-inputs\` from [../load-test-results-fleet.json](../load-test-results-fleet.json). It names no price, no margin and no currency. Credits are mock accounting entries and cannot be bought; pilots are free in the beta; a small fleet is up to 25 agents on the free allowance (owner decision, 2026-11-21). The owner's rule is that no figure is published until the cost per fleet agent has been measured on the hosted service, and nothing below is such a measurement.**

## 1. The measured cost of one agent's writes to the log

The load test (DK1362, run ${r.when.slice(0, 10)}) brought in ${r.agents.toLocaleString("en-GB")} agents and had each sign two acts, in one process on a shared development machine with the in-memory store: ${r.totals.msPerWrite} ms a write (${r.totals.writesPerSecondOneProcess} writes a second in one process), ${r.cost.cpuSecondsPerMillionWrites.toLocaleString("en-GB")} CPU-seconds per million writes, ${r.totals.bytesPerRecord} bytes a record (${r.cost.gigabytesPerMillionRecords} GB per million records, before the database's indexes).

Worked out for one agent for a month of 30 days at three act rates (the act rate is an assumption; the per-write cost is the measurement):

| Acts per agent per day | Writes in the month | CPU-seconds of log work | Megabytes of log records |
|---|---|---|---|
${row(10)}
${row(100)}
${row(1000)}

These are the cost of the signed log alone. They are inputs to a price, not a price.

## 2. What has not been measured

| Cost | Why it is missing | What would measure it |
|---|---|---|
| The hosted database (Postgres) and its indexes | the test used the in-memory store; no database is attached to a builder's machine | the same test against the hosted backend |
| Several processes and the network | one process was measured | a run behind the hosted proxy |
| Reads (the dashboard, the feeds, the pages) | only writes were timed | a read load at the fleet's act rate |
| Support, mail, the host and the people | not a per-write cost | a month of real use on the hosted service |
| The real act rate of a fleet agent | the three rates above are assumptions | one measured month of a pilot (docs/live-run-checklist.md) |

## 3. The structure of a plan, and who decides each part

| Part | Draft | Decided by |
|---|---|---|
| The unit that is metered | an active agent: one that signed at least one act in the month (\`asp meter report\`) | the owner (question 38) |
| Free allowance | up to 25 agents for now | the owner (decided 2026-11-21; may change when the cost is measured) |
| Committed capacity and overage | a committed number of writes and reads a minute, and usage above it | the owner (question 39) |
| Private log, single sign-on, dashboard, support level | what each plan includes (docs/enterprise/plans.md) | the owner, after DK1359 and DK1380 are built |
| The price, the margin and the currency | none | the owner, after a measured month on the hosted service |

## 4. Not claimed

- That any figure above is what a plan will cost, or that the cost of the signed log is the cost of running the service.
- That the load test describes the hosted service: it does not (section 2).
- That anything can be bought today.
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "docs", "enterprise", "pricing-inputs.md"), pricingInputs());
  console.log("wrote docs/enterprise/pricing-inputs.md");
}
